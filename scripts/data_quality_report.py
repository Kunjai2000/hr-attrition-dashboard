"""Create a data quality and suitability report for the attrition dataset.

The report documents availability, structure, completeness and class balance of
the IBM HR Analytics Employee Attrition dataset before any modelling starts.

Usage:
    python scripts/data_quality_report.py
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "data" / "raw" / "WA_Fn-UseC_-HR-Employee-Attrition.csv"
REPORT_PATH = ROOT / "reports" / "data_quality_report.md"
TARGET = "Attrition"
ID_COLUMN = "EmployeeNumber"
SENSITIVE = ["Age", "Gender", "MaritalStatus"]
HOLDOUT_SHARE = 0.20


def sha256_of(path: Path) -> str:
    """Return the SHA-256 hex digest of a file."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def column_overview(df: pd.DataFrame) -> pd.DataFrame:
    """Summarise type, unique values and value range for every column."""
    rows = []
    for col in df.columns:
        series = df[col]
        if pd.api.types.is_numeric_dtype(series):
            kind = "numeric"
            value_range = f"{series.min()} – {series.max()}"
        else:
            kind = "categorical"
            values = sorted(series.astype(str).unique())
            value_range = ", ".join(values) if len(values) <= 6 else f"{len(values)} categories"
        rows.append(
            {
                "column": col,
                "type": kind,
                "unique": series.nunique(),
                "missing": int(series.isna().sum()),
                "range / values": value_range,
            }
        )
    return pd.DataFrame(rows)


def to_markdown_table(frame: pd.DataFrame) -> str:
    """Render a DataFrame as a Markdown table without extra dependencies."""
    header = "| " + " | ".join(frame.columns) + " |"
    divider = "| " + " | ".join("---" for _ in frame.columns) + " |"
    body = [
        "| " + " | ".join(str(value) for value in row) + " |"
        for row in frame.itertuples(index=False)
    ]
    return "\n".join([header, divider, *body])


def build_report(df: pd.DataFrame) -> str:
    """Build the Markdown report text."""
    n_rows, n_cols = df.shape
    counts = df[TARGET].value_counts()
    positives = int(counts.get("Yes", 0))
    negatives = int(counts.get("No", 0))
    rate = positives / n_rows
    constant = [c for c in df.columns if df[c].nunique() == 1]
    usable_features = n_cols - 1 - len(constant) - 1  # minus target, constants, ID
    holdout_positives = round(positives * HOLDOUT_SHARE)

    lines = [
        "# Data quality and suitability report",
        "",
        "Generated by `scripts/data_quality_report.py`.",
        "",
        "## File",
        "",
        f"- Path: `data/raw/{DATA_PATH.name}`",
        f"- SHA-256: `{sha256_of(DATA_PATH)}`",
        "",
        "## Structure and completeness",
        "",
        f"- Records: **{n_rows:,}**, attributes: **{n_cols}**",
        f"- Missing values: **{int(df.isna().sum().sum())}**",
        f"- Duplicate rows: **{int(df.duplicated().sum())}**",
        f"- `{ID_COLUMN}` unique per row: **{df[ID_COLUMN].is_unique}**",
        f"- Constant columns (no information, removed): {', '.join(f'`{c}`' for c in constant)}",
        f"- Usable features after removing constants and ID: **{usable_features}**",
        "",
        "## Target variable",
        "",
        f"- `{TARGET}` = Yes: **{positives}**, No: **{negatives}**",
        f"- Attrition rate: **{rate:.1%}**",
        f"- Accuracy of a naive model that always predicts “No”: **{1 - rate:.1%}**",
        f"- Expected positives in a stratified {HOLDOUT_SHARE:.0%} holdout set: **≈ {holdout_positives}**",
        "  → single holdout values are unstable; repeated stratified 5 × 5 cross-validation is used.",
        "",
        "## Attrition rate by segment (used for the dashboard’s segment views)",
        "",
    ]
    for segment in ["Department", "JobRole", "OverTime"]:
        table = (
            df.groupby(segment)[TARGET]
            .agg(employees="count", leavers=lambda s: int((s == "Yes").sum()))
            .assign(rate=lambda t: (t["leavers"] / t["employees"]).map("{:.1%}".format))
            .reset_index()
        )
        lines += [f"### {segment}", "", to_markdown_table(table), ""]

    lines += [
        "## Sensitive attributes",
        "",
        f"The dataset contains {', '.join(f'`{c}`' for c in SENSITIVE)}. "
        "Their influence on predictions and the option to exclude them are analysed "
        "in the thesis (fairness, GDPR Art. 22, EU AI Act).",
        "",
        "## Column overview",
        "",
        to_markdown_table(column_overview(df)),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Load the dataset, build the report and write it to ``reports/``."""
    df = pd.read_csv(DATA_PATH)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(build_report(df), encoding="utf-8")
    print(f"Report written to {REPORT_PATH}")


if __name__ == "__main__":
    main()
